"""Aggregate the German credit CSV into a small data.js for the showcase site.

Usage: python3 scripts/build_data.py
"""
import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "german_credit_data_biased_training.csv"
OUT = ROOT / "site" / "data.js"

LABELS = {
    "less_0": "< 0 DM", "0_to_200": "0–200 DM", "greater_200": "> 200 DM",
    "no_checking": "No account", "car_new": "New car", "car_used": "Used car",
    "radio_tv": "Radio / TV",
}


def age_band(age):
    for hi, label in ((25, "19–25"), (35, "26–35"), (45, "36–45"), (55, "46–55")):
        if age <= hi:
            return label
    return "56+"


def label(value):
    return LABELS.get(value, value.replace("_", " ").capitalize())


def main():
    rows = list(csv.DictReader(SRC.open()))
    dims = {
        "Sex": lambda r: label(r["Sex"]),
        "Age": lambda r: age_band(int(r["Age"])),
        "LoanPurpose": lambda r: label(r["LoanPurpose"]),
        "Housing": lambda r: label(r["Housing"]),
        "CheckingStatus": lambda r: label(r["CheckingStatus"]),
    }
    out = {"total": len(rows), "risk": sum(r["Risk"] == "Risk" for r in rows), "dims": {}}
    for name, key in dims.items():
        groups = defaultdict(lambda: {"n": 0, "risk": 0, "amount": 0})
        for r in rows:
            g = groups[key(r)]
            g["n"] += 1
            g["risk"] += r["Risk"] == "Risk"
            g["amount"] += int(r["LoanAmount"])
        out["dims"][name] = [
            {"label": k, "n": g["n"], "risk": g["risk"], "avgAmount": round(g["amount"] / g["n"])}
            for k, g in sorted(groups.items())
        ]
    OUT.write_text("// Generated by scripts/build_data.py — do not edit by hand.\n"
                   f"window.CREDIT_DATA = {json.dumps(out, ensure_ascii=False)};\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
